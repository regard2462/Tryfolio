// Platzhalter {0}, {1} fuer Werte. Die Technikfelder (CPC-Unterklassen) haben deutsche und englische Namen.
internal object FirmaFaktenTexte {

    fun text(deutsch: Boolean, key: String, w: List<String> = emptyList()): String {
        var t = (if (deutsch) DE else EN)[key] ?: return ""
        w.forEachIndexed { i, v -> t = t.replace("{$i}", v) }
        return t
    }

    // In der Sprache der App
    fun t(key: String, vararg w: String): String = text(I18n.lang == Lang.DE, key, w.toList())

    // Name eines Landes im EU-Emissionshandel (Registerkuerzel); unbekannte Kuerzel bleiben stehen
    fun land(code: String): String = LAENDER[code]?.let { if (I18n.lang == Lang.DE) it.first else it.second } ?: code

    // Alle Schluessel einer Sprache (der Test vergleicht beide Sprachen)
    fun schluessel(deutsch: Boolean): Set<String> = (if (deutsch) DE else EN).keys

    // Name einer CPC-Unterklasse (vier Zeichen); ohne Eintrag der Name des Abschnitts (erstes Zeichen)
    fun cpcName(deutsch: Boolean, code: String): String {
        val e = CPC[code]
        if (e != null) return if (deutsch) e.first else e.second
        val a = ABSCHNITT[code.take(1)] ?: return code
        return if (deutsch) a.first else a.second
    }

    // Name in der Sprache der App
    fun cpc(code: String): String = cpcName(I18n.lang == Lang.DE, code)

