#!/usr/bin/env python3
# Baut drei verdichtete Dateien fuer den Abschnitt "Waehrung und Kaufkraft" und die Ranglisten des Laenderblatts:
#
#   app/src/main/assets/globus/waehrung.json     Wechselkurs zum Dollar im Jahresschnitt und realer effektiver Wechselkurs (jaehrlich)
#   app/src/main/assets/globus/bigmac.json       Big-Mac-Index (halbjaehrlich)
#   app/src/main/assets/globus/ranglisten.json   Laenderindizes: menschliche Entwicklung, Ungleichheit, Logistik, Humankapital
#
# Quellen und Bedingungen (am 12.11.2026 auf den Seiten der Quellen gelesen):
#   - Weltbank, World Development Indicators (https://data.worldbank.org/), CC BY 4.0: PA.NUS.FCRF (Wechselkurs im
#     Jahresschnitt, Landeswaehrung je US-Dollar), PX.REX.REER (realer effektiver Wechselkurs, 2010 = 100), SI.POV.GINI,
#     LP.LPI.OVRL.XQ, HD.HCI.OVRL.
#   - The Economist, Big Mac index (https://github.com/TheEconomist/big-mac-data), README, Abschnitt Licence: "The data
#     generated by The Economist are available under the Creative Commons Attribution 4.0 International License." und
#     "The licences include only the data and the software authored by The Economist, and do not cover any Economist
#     content or third-party data or content made available using the software." Darum stehen in der Datei nur die Preise
#     und die von The Economist gerechneten Indexwerte, nicht die Wechselkurse (Reuters, Refinitiv) und nicht das BIP je
#     Kopf (IWF) aus der Tabelle.
#   - UNDP, Human Development Report (https://hdr.undp.org/terms-use): "All materials provided on this website are
#     copyrighted under the Creative Commons Attribution 3.0 IGO license." Verlangt: Namensnennung, Link zur Lizenz,
#     Hinweis auf Aenderungen. Die Datei traegt die Werte unveraendert (gerundet auf drei Stellen wie in der Quelle).
#
# Aufruf:
#   python tools/daten/kaufkraft.py holen <Ordner>                      laedt die Tabellen (Browserkennung, kein Konto)
#   python tools/daten/kaufkraft.py bauen <Ordner> --stand=JJJJ-MM-TT   liest die Tabellen aus dem Ordner
# Danach: python tools/daten/manifest.py bauen   (nicht signieren)

import csv
import io
import json
import math
import os
import sys
import time
import urllib.request

KENNUNG = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
WB = "https://api.worldbank.org/v2/country/all/indicator/%s?format=json&per_page=20000&date=%d:%d"
WB_LAENDER = "https://api.worldbank.org/v2/country?format=json&per_page=400"
BIGMAC_URL = "https://raw.githubusercontent.com/TheEconomist/big-mac-data/master/output-data/big-mac-full-index.csv"
UNDP_URL = "https://hdr.undp.org/sites/default/files/2025_HDR/HDR25_Composite_indices_complete_time_series.csv"

AB = 2000
BIS = 2026
# Reihen mit Verlauf und Indizes mit dem juengsten Wert je Land
REIHEN = {"PA.NUS.FCRF": "f", "PX.REX.REER": "r"}
INDIZES = {"SI.POV.GINI": "gini", "LP.LPI.OVRL.XQ": "lpi", "HD.HCI.OVRL": "hci"}
# Kuerzel der Weltbank -> Kuerzel der Karte
UMBENANNT = {"XKX": "KOS"}
# Big-Mac-Tabelle: Kuerzel des Euroraums
EURORAUM = "EUZ"


def repo():
    return os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


def holen_datei(url, ziel):
    r = urllib.request.Request(url, headers={"User-Agent": KENNUNG})
    with urllib.request.urlopen(r, timeout=180) as a:
        b = a.read()
    with open(ziel, "wb") as f:
        f.write(b)
    print("%s: %d Bytes" % (os.path.basename(ziel), len(b)))


def lesen_json(pfad):
    with open(pfad, "rb") as f:
        return json.loads(f.read().decode("utf-8-sig"))


def rund(x, stellen=5):
    # Auf geltende Stellen gerundet, ganze Zahlen ohne Komma
    if x is None:
        return None
    v = float("%.*g" % (stellen, x))
    return int(v) if v == int(v) and abs(v) < 1e15 else v


def laender(ordner):
    # Nur Laender und Gebiete, keine Regionen und Einkommensgruppen
    aus = set()
    for e in lesen_json(os.path.join(ordner, "wb-laender.json"))[1]:
        if e["region"]["id"] != "NA" and len(e["id"]) == 3:
            aus.add(e["id"])
    return aus


def wb_reihe(ordner, kennung, gueltig):
    # {Land: {Jahr: Wert}}
    aus = {}
    for e in lesen_json(os.path.join(ordner, "wb-%s.json" % kennung))[1] or []:
        code = e.get("countryiso3code") or ""
        if code not in gueltig or e.get("value") is None:
            continue
        aus.setdefault(UMBENANNT.get(code, code), {})[int(e["date"][:4])] = float(e["value"])
    return aus


# Beitritt zum Euro: Jahr und unwiderruflicher Umrechnungskurs (alte Waehrung je Euro, Verordnungen des Rates). Die Weltbank
# fuehrt die Jahre davor in der alten Waehrung; damit der Verlauf nicht springt, stehen sie hier in Euro umgerechnet.
EURO_BEITRITT = {
    "GRC": (2001, 340.750), "SVN": (2007, 239.640), "CYP": (2008, 0.585274), "MLT": (2008, 0.429300), "SVK": (2009, 30.1260),
    "EST": (2011, 15.6466), "LVA": (2014, 0.702804), "LTU": (2015, 3.45280), "HRV": (2023, 7.53450), "BGR": (2026, 1.95583),
}


def euro_umrechnen(kurse):
    # kurse: {Land: {Jahr: Landeswaehrung je Dollar}}. Rechnet nur um, wenn die Reihe vor dem Beitritt wirklich in der alten
    # Waehrung steht (Verhaeltnis zum Kurs Deutschlands naeher am Umrechnungskurs als an 1).
    euro = kurse.get("DEU", {})
    for land, (jahr, kurs) in EURO_BEITRITT.items():
        reihe = kurse.get(land)
        if not reihe:
            continue
        for j in list(reihe):
            e = euro.get(j)
            if j >= jahr or not e:
                continue
            v = reihe[j] / e
            if abs(math.log(v / kurs)) < abs(math.log(v)):
                reihe[j] = reihe[j] / kurs


def waehrung_bauen(ordner, stand):
    gueltig = laender(ordner)
    je = {k: wb_reihe(ordner, kennung, gueltig) for kennung, k in REIHEN.items()}
    euro_umrechnen(je["f"])
    bis = max(j for r in je.values() for l in r.values() for j in l)
    aus = {}
    for k, r in je.items():
        for land, jahre in r.items():
            werte = [rund(jahre.get(j)) for j in range(AB, bis + 1)]
            if sum(1 for x in werte if x is not None) >= 2:
                aus.setdefault(land, {})[k] = werte
    return {
        "stand": stand, "schema": 1, "ab": AB, "bis": bis,
        "quelle": "World Bank, World Development Indicators (https://data.worldbank.org/), CC BY 4.0, abgerufen am " + stand,
        "einheit": "f: Landeswaehrung je US-Dollar im Jahresschnitt; r: realer effektiver Wechselkurs, 2010 = 100",
        "l": dict(sorted(aus.items())),
    }


def bigmac_bauen(ordner, stand):
    with open(os.path.join(ordner, "big-mac-full-index.csv"), "rb") as f:
        zeilen = list(csv.DictReader(io.StringIO(f.read().decode("utf-8-sig"))))
    tage = sorted({z["date"] for z in zeilen})
    nr = {t: i for i, t in enumerate(tage)}

    def zahl(z, k):
        try:
            v = float(z[k])
        except (KeyError, ValueError):
            return None
        return v if v == v else None

    je = {}
    for z in zeilen:
        je.setdefault(z["iso_a3"], {})[z["date"]] = z
    aus = {}
    for a3, reihe in sorted(je.items()):
        letzter = max(reihe)
        z = reihe[letzter]
        roh = [None] * len(tage)
        for t, zz in reihe.items():
            v = zahl(zz, "USD_raw")
            roh[nr[t]] = None if v is None else int(round(v * 1000))
        o = {
            "w": z["currency_code"], "t": nr[letzter], "lp": rund(zahl(z, "local_price")), "dp": rund(zahl(z, "dollar_price"), 4),
            "ur": roh,
        }
        for k, spalte in (("er", "EUR_raw"), ("ua", "USD_adjusted"), ("ea", "EUR_adjusted")):
            v = zahl(z, spalte)
            if v is not None:
                o[k] = int(round(v * 1000))
        aus[a3] = o
    if EURORAUM not in aus or "USA" not in aus:
        raise SystemExit("Euroraum oder USA fehlen in der Big-Mac-Tabelle")
    return {
        "stand": stand, "schema": 1, "tage": tage,
        "quelle": "The Economist, The Big Mac index (https://github.com/TheEconomist/big-mac-data), CC BY 4.0, abgerufen am " + stand,
        "einheit": "lp: Preis in Landeswaehrung; dp: Preis in US-Dollar; ur, er, ua, ea: Abweichung in Promille (roh und "
                   "BIP-bereinigt, gegen Dollar und Euro); ur je Stichtag aus tage, die uebrigen am Stichtag t",
        "l": aus,
    }


def ranglisten_bauen(ordner, stand):
    gueltig = laender(ordner)
    indizes = {}
    for kennung, k in INDIZES.items():
        w = {}
        for land, jahre in wb_reihe(ordner, kennung, gueltig).items():
            j = max(jahre)
            w[land] = [j, rund(jahre[j], 4)]
        indizes[k] = dict(sorted(w.items()))
    with open(os.path.join(ordner, "undp.csv"), "rb") as f:
        zeilen = list(csv.DictReader(io.StringIO(f.read().decode("utf-8-sig", "replace"))))
    kopf = zeilen[0].keys()
    hdi_reihe = {}
    for k, vor in (("hdi", "hdi_"), ("ihdi", "ihdi_"), ("gii", "gii_")):
        jahre = sorted(int(s[len(vor):]) for s in kopf if s.startswith(vor) and s[len(vor):].isdigit())
        w = {}
        for z in zeilen:
            a3 = z["iso3"]
            if len(a3) != 3 or a3.startswith("ZZ"):
                continue
            for j in reversed(jahre):
                s = (z.get(vor + str(j)) or "").strip()
                try:
                    v = float(s)
                except ValueError:
                    continue
                w[a3] = [j, rund(v, 4)]
                break
            if k == "hdi":
                reihe = []
                for j in jahre:
                    try:
                        reihe.append(int(round(float(z.get(vor + str(j)) or "") * 1000)))
                    except ValueError:
                        reihe.append(None)
                if sum(1 for x in reihe if x is not None) >= 2:
                    hdi_reihe[a3] = reihe
        indizes[k] = dict(sorted(w.items()))
        if k == "hdi":
            hdi_ab = jahre[0]
    return {
        "stand": stand, "schema": 1,
        "quelle": "UNDP, Human Development Report (https://hdr.undp.org/), CC BY 3.0 IGO; World Bank, World Development "
                  "Indicators (https://data.worldbank.org/), CC BY 4.0; abgerufen am " + stand,
        "einheit": "i: je Index und Land [Jahr, Wert]; hdi: Verlauf in Tausendsteln ab hdiAb",
        "i": indizes, "hdiAb": hdi_ab, "hdi": dict(sorted(hdi_reihe.items())),
    }


def schreiben(datei, name):
    ziel = os.path.join(repo(), "app", "src", "main", "assets", "globus", name)
    text = json.dumps(datei, ensure_ascii=False, separators=(",", ":")) + chr(10)
    with open(ziel, "w", encoding="utf-8", newline=chr(10)) as f:
        f.write(text)
    print("%s: %d Bytes" % (name, len(text.encode("utf-8"))))


def hauptteil():
    if len(sys.argv) < 3 or sys.argv[1] not in ("holen", "bauen"):
        raise SystemExit(__doc__)
    ordner = sys.argv[2]
    stand = next((a[len("--stand="):] for a in sys.argv[3:] if a.startswith("--stand=")), None)
    if sys.argv[1] == "holen":
        os.makedirs(ordner, exist_ok=True)
        holen_datei(WB_LAENDER, os.path.join(ordner, "wb-laender.json"))
        for kennung in list(REIHEN) + list(INDIZES):
            time.sleep(2)
            ab = AB if kennung in REIHEN else BIS - 12
            holen_datei(WB % (kennung, ab, BIS), os.path.join(ordner, "wb-%s.json" % kennung))
        holen_datei(BIGMAC_URL, os.path.join(ordner, "big-mac-full-index.csv"))
        holen_datei(UNDP_URL, os.path.join(ordner, "undp.csv"))
        return
    if not stand:
        raise SystemExit("--stand=JJJJ-MM-TT angeben (Tag des Abrufs)")
    schreiben(waehrung_bauen(ordner, stand), "waehrung.json")
    schreiben(bigmac_bauen(ordner, stand), "bigmac.json")
    schreiben(ranglisten_bauen(ordner, stand), "ranglisten.json")


if __name__ == "__main__":
    hauptteil()
